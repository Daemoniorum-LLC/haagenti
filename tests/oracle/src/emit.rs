//! Writing (or, with --check, comparing) ../expected/*.txt and ../consumer/src/gen_*.sg.
//!
//! A data row is five fields: tag, three names and a hex string. In Sigil it is `tag, a, b, c, n`
//! and then n chunks of at most 4,096 hex digits, one string a line. A part (one rite) holds at most
//! 70 lines and a file at most three parts, to keep under 80 lines a rite and 300 a file.

use std::path::PathBuf;

const CHUNK: usize = 4096;
const PART_LINES: usize = 70;
const FILE_PARTS: usize = 3;

pub fn hex(x: &[u8]) -> String {
    x.iter().map(|b| format!("{b:02x}")).collect()
}

pub struct Out {
    check: bool,
    differ: Vec<String>,
    stems: Vec<(String, usize)>,
}

fn gen_dir() -> PathBuf {
    root().join("consumer").join("src").join("gen")
}

fn root() -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("..")
}

impl Out {
    pub fn new(check: bool) -> Self {
        Out { check, differ: vec![], stems: vec![] }
    }

    fn put(&mut self, path: PathBuf, body: String) {
        if self.check {
            if std::fs::read_to_string(&path).ok().as_deref() != Some(body.as_str()) {
                self.differ.push(path.display().to_string());
            }
        } else {
            std::fs::create_dir_all(path.parent().unwrap()).unwrap();
            std::fs::write(&path, body).unwrap();
        }
    }

    pub fn text(&mut self, file: &str, what: &str, rows: &[String]) {
        let mut body = format!("# GENERATED by tests/oracle (LARES-932): {what}. {} rows.\n", rows.len());
        for r in rows {
            body.push_str(r);
            body.push('\n');
        }
        self.put(root().join("expected").join(file), body);
    }

    /// Generated Sigil data: `<stem>_<k>.sg` files, each `☉ rite <stem>_<k>(part) → Vec<&str>`, and
    /// rites giving the counts of parts.
    pub fn data(&mut self, stem: &str, what: &str, rows: &[Vec<String>]) {
        let mut lines: Vec<Vec<String>> = vec![vec![]];
        for row in rows {
            let chunks: Vec<&str> = if row[4].is_empty() { vec![] } else {
                row[4].as_bytes().chunks(CHUNK).map(|c| std::str::from_utf8(c).unwrap()).collect()
            };
            let mut l = vec![format!("\"{}\", \"{}\", \"{}\", \"{}\", \"{}\",", row[0], row[1], row[2], row[3], chunks.len())];
            l.extend(chunks.iter().map(|c| format!("\"{c}\",")));
            // a row is never split across parts
            if lines.last().unwrap().len() + l.len() > PART_LINES && !lines.last().unwrap().is_empty() {
                lines.push(vec![]);
            }
            lines.last_mut().unwrap().extend(l);
        }
        let files: Vec<&[Vec<String>]> = lines.chunks(FILE_PARTS).collect();
        for (k, parts) in files.iter().enumerate() {
            let name = format!("{stem}_{k}");
            let mut b = format!("//! GENERATED by tests/oracle (LARES-932): {what}, file {} of {}. Edit the oracle, not this file.\n\n",
                                k + 1, files.len());
            b.push_str(&format!("☉ rite {name}_parts() → i64 {{ {} }}\n\n", parts.len()));
            b.push_str(&format!("☉ rite {name}(part: i64) → Vec<&str> {{\n"));
            for p in 0..parts.len() {
                b.push_str(&format!("    ⎇ part == {p} {{ ⤺ {name}_p{p}(); }}\n"));
            }
            b.push_str("    Vec·new()\n}\n");
            for (p, part) in parts.iter().enumerate() {
                b.push_str(&format!("\nrite {name}_p{p}() → Vec<&str> {{\n    vec![\n"));
                for l in part.iter() {
                    b.push_str(&format!("        {l}\n"));
                }
                b.push_str("    ]\n}\n");
            }
            self.put(gen_dir().join(format!("{name}.sg")), b);
        }
        self.stems.push((stem.to_string(), files.len()));
    }

    /// gen/mod.sg: declares every generated scroll and gives `<stem>(file, part)`, `<stem>_parts(file)`
    /// and `<stem>_files()` (rites, not `◆`: spec §7 K4), so the consumer reaches them all without naming each.
    fn index(&mut self) {
        let mut b = String::from("//! GENERATED by tests/oracle (LARES-932): the index of the generated data scrolls.\n\n");
        for (stem, n) in &self.stems {
            for k in 0..*n {
                b.push_str(&format!("scroll {stem}_{k};\n"));
            }
        }
        for (stem, n) in self.stems.clone() {
            b.push_str(&format!("\n☉ rite {stem}_files() → i64 {{ {n} }}\n"));
            for (rite, what) in [("", "(part)"), ("_parts", "")] {
                let ty = if rite.is_empty() { "Vec<&str>" } else { "i64" };
                let arg = if rite.is_empty() { ", part: i64" } else { "" };
                b.push_str(&format!("\n☉ rite {stem}{rite}(file: i64{arg}) → {ty} {{\n"));
                for k in 0..n {
                    let call = if rite.is_empty() { format!("tome·gen·{stem}_{k}·{stem}_{k}{what}") }
                               else { format!("tome·gen·{stem}_{k}·{stem}_{k}_parts()") };
                    b.push_str(&format!("    ⎇ file == {k} {{ ⤺ {call}; }}\n"));
                }
                b.push_str(if rite.is_empty() { "    Vec·new()\n}\n" } else { "    0\n}\n" });
            }
        }
        self.put(gen_dir().join("mod.sg"), b);
    }

    /// 0 written or every file the same; 1 with --check and a file differs.
    pub fn finish(mut self) -> i32 {
        self.index();
        for d in &self.differ {
            eprintln!("differs from what the oracle writes: {d}");
        }
        i32::from(!self.differ.is_empty())
    }
}
